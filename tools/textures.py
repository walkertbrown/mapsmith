# Turns the painted textures in art/ into src/textures.ts: each one made to wrap at its edges
# (the organic ones get their edges blended into the opposite side), shrunk, and kept as a data URI.
import base64, io, sys
from PIL import Image

SIZE = 256
BLEND = {'rock', 'cave', 'grass', 'water'}  # built ones (stone, wood, cobble) already wrap and would ghost
NAMES = ['stone', 'wood', 'rock', 'cave', 'cobble', 'grass', 'water', 'plate', 'grate', 'bay']

def wrap(im):
    # mix in the image shifted by half, weighted toward it only near the edges
    w, h = im.size
    sh = Image.new('RGB', (w, h))
    sh.paste(im.crop((w // 2, 0, w, h)), (0, 0)); sh.paste(im.crop((0, 0, w // 2, h)), (w - w // 2, 0))
    sh2 = Image.new('RGB', (w, h))
    sh2.paste(sh.crop((0, h // 2, w, h)), (0, 0)); sh2.paste(sh.crop((0, 0, w, h // 2)), (0, h - h // 2))
    band = w // 8
    mask = Image.new('L', (w, h))
    px = mask.load()
    for y in range(h):
        for x in range(w):
            d = min(x, w - 1 - x, y, h - 1 - y)
            px[x, y] = 255 if d < 1 else max(0, int(255 * (1 - d / band))) if d < band else 0
    return Image.composite(sh2, im, mask)

out = ['// Generated by tools/textures.py from art/; do not edit by hand.', '']
for n in NAMES:
    im = Image.open(f'art/{n}.jpg').convert('RGB')
    if n in BLEND: im = wrap(im)
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'JPEG', quality=72, optimize=True, progressive=True)
    out.append(f"export const {n.upper()} = 'data:image/jpeg;base64,{base64.b64encode(buf.getvalue()).decode()}';")
    print(n, len(buf.getvalue()), file=sys.stderr)
open('src/textures.ts', 'w').write('\n'.join(out) + '\n')
